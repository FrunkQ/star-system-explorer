// V3 colours into V4 (V12). Where V3 keeps colours decides where they land
// (docs/v3-colours.md):
// - Palette overrides are the viewer's, in V3's localStorage key
//   `sse-palette-overrides` ({ token: hex }). They become an edited copy of
//   the symbology on this device (a view setting), never campaign data.
// - A V3 save carries `coiCategories` (tag categories the GM changed, with
//   color/textColor) and per-object colours. Category colours go on the
//   symbology as tag colours. Per-object colours are object facts: authored
//   ones arrive with the save importer (P3) as authored events, and the
//   derived true colour (`apparentColorHex`) is recomputed by V4. This
//   module only lists them, so the GM sees what the save held.
// Presentation only: nothing here reaches the kernel.
import type { Json } from "./json.ts";
import { checkSymbology, resolveSymbology, type Binding, type SymbologyDoc, type TagColour } from "./symbology.ts";

/** How each V3 token lands (generated by scripts/make-symbologies.py as v3-colour-tokens.json). */
export interface V3TokenMap {
  schema: "sse.v3-colour-tokens/0";
  tokens: Record<string, { group: string; classes?: string[]; tags?: string; values?: string[]; kind?: string; spectral?: string }>;
}

export interface V3ImportLine {
  token: string;
  hex?: string;
  /** What it changed ("43 terrestrial classes", "K stars"), or why it was left. */
  note: string;
}

export interface V3PaletteImport {
  doc: SymbologyDoc;
  applied: V3ImportLine[];
  skipped: V3ImportLine[];
}

const HEX = /^#[0-9A-Fa-f]{6}$/;
const SHORT_HEX = /^#[0-9A-Fa-f]{3}$/;
const CHROME = /^--(bg|surface|panel|text|fg|muted|accent|border|focus|link|success|warning|danger|error|info|shadow|overlay|scrim|chrome|ui)/;

function hexOf(v: unknown): string | null {
  if (typeof v !== "string") return null;
  const s = v.trim();
  if (HEX.test(s)) return s.toLowerCase();
  if (SHORT_HEX.test(s)) return `#${s[1]}${s[1]}${s[2]}${s[2]}${s[3]}${s[3]}`.toLowerCase();
  return null;
}

/** Read the pasted or loaded value of V3's `sse-palette-overrides`. Returns the map, or why it is not one. */
export function parseV3Palette(text: string): Record<string, string> | string {
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch {
    return "This is not JSON. Paste the value of sse-palette-overrides from V3 (an object of token to colour).";
  }
  // A whole localStorage dump is fine too: take the key out of it.
  if (raw && typeof raw === "object" && !Array.isArray(raw) && "sse-palette-overrides" in raw) {
    const inner = (raw as Record<string, unknown>)["sse-palette-overrides"];
    raw = typeof inner === "string" ? (JSON.parse(inner) as unknown) : inner;
  }
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return "Expected an object of token to colour, like {\"--body-gas-giant\": \"#cc0000\"}.";
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(raw as Record<string, unknown>)) if (typeof v === "string") out[k.startsWith("--") ? k : `--${k}`] = v;
  if (Object.keys(out).length === 0) return "No colours in it.";
  return out;
}

/** The campaign's edited copy to change: the kept one, or a new copy of the chosen symbology. */
export function campaignCopy(chosenId: string, registry: readonly SymbologyDoc[], id = "campaign.symbology"): SymbologyDoc {
  const have = registry.find((d) => d.id === id);
  if (have) return JSON.parse(JSON.stringify(have)) as SymbologyDoc;
  const chosen = registry.find((d) => d.id === chosenId);
  return { schema: "sse.symbology/1", id, name: "Campaign symbols", description: `${chosen?.name ?? chosenId}, changed for this campaign.`, inherits: chosenId, mix: {}, bindings: [] };
}

/** The doc's own binding for (kind, colour, from), copied from what is in force (or from colour-coded) when it has none. */
function colourBinding(d: SymbologyDoc, registry: readonly SymbologyDoc[], appliesTo: string, from: string): Binding {
  const own = d.bindings.find((b) => b.applies_to === appliesTo && b.channel === "colour" && b.from === from && !b.when);
  if (own) return own;
  const reg = [...registry.filter((x) => x.id !== d.id), d];
  const inForce = (id: string) => {
    try {
      return resolveSymbology(id, reg).find((b) => b.applies_to === appliesTo && b.channel === "colour" && b.from === from && !b.when);
    } catch {
      return undefined;
    }
  };
  const seed = inForce(d.id) ?? inForce("sse.symbology.colour-coded");
  const b: Binding = seed ? (JSON.parse(JSON.stringify(seed)) as Binding) : { applies_to: appliesTo, channel: "colour", from, scale: { table: {} }, fallback: null };
  d.bindings = [...d.bindings.filter((x) => !(x.applies_to === appliesTo && x.channel === "colour" && x.from === from)), b];
  return b;
}

function table(b: { scale: Binding["scale"] }): Record<string, string | number | boolean> {
  if (!("table" in b.scale)) b.scale = { table: {} };
  return (b.scale as { table: Record<string, string | number | boolean> }).table;
}

/**
 * Apply V3 palette overrides to the campaign's copy of the symbology. Body
 * and star tokens change the colours V3 used them for; theme tokens (surfaces,
 * text, accent) and the other domain tokens (zones, hazards, bands) are left,
 * each with the reason, because in V4 those belong to the theme or to views
 * that do not draw them yet.
 */
export function symbologyFromV3Palette(overrides: Record<string, string>, map: V3TokenMap, chosenId: string, registry: readonly SymbologyDoc[]): V3PaletteImport {
  const doc = campaignCopy(chosenId, registry);
  const applied: V3ImportLine[] = [];
  const skipped: V3ImportLine[] = [];
  for (const [token, value] of Object.entries(overrides).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const hex = hexOf(value);
    const m = map.tokens[token];
    if (!m) {
      skipped.push({ token, note: CHROME.test(token) ? "A theme colour: in V4 the theme of each view sets it, not the symbols." : "No V4 symbol draws this yet (zones, hazards, bands and data marks come with their views)." });
      continue;
    }
    if (!hex) {
      skipped.push({ token, note: `"${value}" is not a plain colour (#RRGGBB).` });
      continue;
    }
    if (m.classes) {
      const t = table(colourBinding(doc, registry, "planet", "class"));
      for (const c of m.classes) t[c] = hex;
      applied.push({ token, hex, note: `${m.classes.length} ${m.classes.length === 1 ? "class" : "classes"} (V3's ${m.group} colour)` });
    } else if (m.tags && m.values) {
      const b = colourBinding(doc, registry, "planet", "class");
      const prefer = (b.prefer ??= []);
      let p = prefer.find((x) => x.from === `tag:${m.tags}`);
      if (!p) prefer.unshift((p = { from: `tag:${m.tags}`, scale: { table: {} } }));
      const t = table(p);
      for (const v of m.values) t[v] = hex;
      applied.push({ token, hex, note: `worlds tagged ${m.values.map((v) => m.tags + v).join(" or ")}` });
    } else if (m.spectral) {
      table(colourBinding(doc, registry, "star", "tag:spectral:"))[m.spectral] = hex;
      applied.push({ token, hex, note: `${m.spectral} stars` });
    } else if (m.kind) {
      table(colourBinding(doc, registry, m.kind, "kind"))[m.kind] = hex;
      applied.push({ token, hex, note: `${m.kind === "station" ? "constructs without their own icon colour" : `${m.kind}s`}` });
    } else skipped.push({ token, note: "No V4 symbol draws this yet." });
  }
  const bad = checkSymbology(doc, registry);
  if (bad) throw new Error(`imported symbology is malformed: ${bad}`);
  return { doc, applied, skipped };
}

/** One colour a V3 save holds on an object. */
export interface V3ObjectColour {
  /** The object's V3 id and name, where the save gives them. */
  id?: string;
  name?: string;
  field: string;
  hex: string;
  /** authored: arrives with the save importer as an authored fact. derived: V4 recomputes it. */
  class: "authored" | "derived";
}

export interface V3SaveColours {
  /** Tag categories the GM changed (V3 saves only those), by category id. */
  tag_colours: Record<string, TagColour>;
  objects: V3ObjectColour[];
}

const OBJECT_FIELDS: Record<string, "authored" | "derived"> = { colorHex: "authored", lightHex: "authored", icon_color: "authored", exhaust_color_hex: "authored", apparentColorHex: "derived" };

/** The colours a V3 save (starmap.json or system.json, parsed) holds, by where V3 keeps them. */
export function coloursFromV3Save(save: Json): V3SaveColours {
  const tag_colours: Record<string, TagColour> = {};
  const objects: V3ObjectColour[] = [];
  const cats = (o: unknown): void => {
    if (!Array.isArray(o)) return;
    for (const c of o) {
      if (!c || typeof c !== "object" || typeof (c as { id?: unknown }).id !== "string") continue;
      const k = c as { id: string; label?: unknown; color?: unknown; textColor?: unknown };
      const t: TagColour = {};
      if (typeof k.label === "string") t.label = k.label;
      const col = hexOf(k.color);
      const txt = hexOf(k.textColor);
      if (col) t.color = col;
      if (txt) t.textColor = txt;
      if (t.color || t.textColor) tag_colours[k.id] = t;
    }
  };
  const walk = (v: unknown, owner: { id?: string; name?: string }, path: string): void => {
    if (Array.isArray(v)) {
      v.forEach((x, i) => walk(x, owner, `${path}[${i}]`));
      return;
    }
    if (!v || typeof v !== "object") return;
    const o = v as Record<string, unknown>;
    const here = typeof o.id === "string" && (typeof o.name === "string" || "kind" in o || "parentId" in o) ? { id: o.id, name: typeof o.name === "string" ? o.name : undefined } : owner;
    const base = here === owner ? path : "";
    const at = (k: string) => (base ? `${base}.${k}` : k);
    for (const [k, x] of Object.entries(o)) {
      if (k === "coiCategories") {
        cats(x);
        continue;
      }
      const cls = OBJECT_FIELDS[k];
      const hex = cls ? hexOf(x) : null;
      if (cls && hex) {
        const rec: V3ObjectColour = { field: at(k), hex, class: cls };
        if (here.id !== undefined) rec.id = here.id;
        if (here.name !== undefined) rec.name = here.name;
        objects.push(rec);
      } else walk(x, here, at(k));
    }
  };
  walk(save, {}, "");
  return { tag_colours, objects };
}

/** Put a save's tag category colours on the campaign's copy of the symbology (category by category). */
export function withV3TagColours(doc: SymbologyDoc, colours: V3SaveColours): SymbologyDoc {
  const out = JSON.parse(JSON.stringify(doc)) as SymbologyDoc;
  out.tag_colours = { ...(out.tag_colours ?? {}), ...colours.tag_colours };
  if (Object.keys(out.tag_colours).length === 0) delete out.tag_colours;
  return out;
}

/** A short account of a save's object colours, for the import report. */
export function objectColourSummary(objects: readonly V3ObjectColour[]): string[] {
  const authored = objects.filter((o) => o.class === "authored");
  const derived = objects.filter((o) => o.class === "derived");
  const lines: string[] = [];
  if (authored.length) {
    const kinds = [...new Set(authored.map((o) => o.field.split(".").pop()!))].sort();
    lines.push(`${authored.length} authored object ${authored.length === 1 ? "colour" : "colours"} (${kinds.join(", ")}): these are facts of the objects and arrive with the save import as authored values.`);
  }
  if (derived.length) lines.push(`${derived.length} derived true ${derived.length === 1 ? "colour" : "colours"} (apparentColorHex): V4 recomputes these and does not take V3's.`);
  return lines;
}

/**
 * The JSON inside a V3 `.sse.zip` (starmap.json, else system.json), read with
 * the platform's own inflate. Plain JSON text comes back unchanged.
 */
export async function v3SaveText(bytes: Uint8Array): Promise<string> {
  const isZip = bytes.length > 4 && bytes[0] === 0x50 && bytes[1] === 0x4b && bytes[2] === 0x03 && bytes[3] === 0x04;
  if (!isZip) return new TextDecoder().decode(bytes);
  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  let eocd = -1;
  for (let i = bytes.length - 22; i >= Math.max(0, bytes.length - 65557); i--) {
    if (dv.getUint32(i, true) === 0x06054b50) {
      eocd = i;
      break;
    }
  }
  if (eocd < 0) throw new Error("not a readable zip");
  const count = dv.getUint16(eocd + 10, true);
  let p = dv.getUint32(eocd + 16, true);
  const entries: { name: string; method: number; size: number; local: number }[] = [];
  for (let n = 0; n < count; n++) {
    if (dv.getUint32(p, true) !== 0x02014b50) throw new Error("zip directory is damaged");
    const method = dv.getUint16(p + 10, true);
    const size = dv.getUint32(p + 20, true);
    const nameLen = dv.getUint16(p + 28, true);
    const extra = dv.getUint16(p + 30, true);
    const comment = dv.getUint16(p + 32, true);
    const local = dv.getUint32(p + 42, true);
    entries.push({ name: new TextDecoder().decode(bytes.subarray(p + 46, p + 46 + nameLen)), method, size, local });
    p += 46 + nameLen + extra + comment;
  }
  const pick = entries.find((e) => /(^|\/)starmap\.json$/.test(e.name)) ?? entries.find((e) => /(^|\/)system\.json$/.test(e.name));
  if (!pick) throw new Error("no starmap.json or system.json in the zip");
  const lh = pick.local;
  const start = lh + 30 + dv.getUint16(lh + 26, true) + dv.getUint16(lh + 28, true);
  const data = bytes.subarray(start, start + pick.size);
  if (pick.method === 0) return new TextDecoder().decode(data);
  if (pick.method !== 8) throw new Error(`zip entry uses compression ${pick.method}`);
  const stream = new Blob([data as BlobPart]).stream().pipeThrough(new DecompressionStream("deflate-raw"));
  return await new Response(stream).text();
}
