//! F7: the long life of a *generated* system. A formation run (stages 1 to 8,
//! `sse_formation::pipeline`) becomes the ageing engine's `SystemSpec`, the
//! system is aged to a target date, and the formation story (impacts,
//! geology falling quiet) and the ageing story (the star brightening, oceans
//! lost, engulfment, the white dwarf) are merged into one dated timeline.

use crate::epoch::{Ageing, AgeingRun, DebrisSpec, PlanetSpec, SystemSpec, TimeSettings};
use serde::{Deserialize, Serialize};
use sse_core::math as m;
use sse_core::{Draws, Seed, Stream};
use sse_formation::early::Envelope;
use sse_formation::pipeline::SystemRun;

/// Mutual inclinations of compact multi-planet systems: Rayleigh with a
/// scale of about 1.5 degrees (Fabrycky et al. 2014, ApJ 790, 146).
pub const INCLINATION_SCALE_DEG: f64 = 1.5;

/// One line of the merged story.
#[derive(Clone, PartialEq, Debug, Serialize, Deserialize)]
pub struct StoryLine {
    /// Star age, Myr.
    pub age_myr: f64,
    pub kind: String,
    pub subjects: Vec<String>,
    pub text: String,
    /// "formation" or "ageing".
    pub from: String,
}

#[derive(Clone, PartialEq, Debug, Serialize, Deserialize)]
pub struct LongLife {
    pub spec: SystemSpec,
    pub run: AgeingRun,
    /// Close binary interactions up to the target date (rule table, sketch).
    pub binaries: Vec<crate::binary::Interaction>,
    pub story: Vec<StoryLine>,
}

/// The ageing engine's view of a formed system. Orbits from growth; angles
/// drawn per world (keyed by address, so a world keeps its angles however
/// many worlds the system has); oceans where early life left surface water.
pub fn spec_from_run(run: &SystemRun) -> SystemSpec {
    let h = &run.history;
    let seed = Seed::from_text(&h.manifest.seed);
    let mut planets = vec![];
    for (p, w) in run.protoplanets.iter().zip(&run.worlds) {
        let d = Draws::new(
            seed,
            p.address.clone(),
            Stream::new("time.generated.v1").expect("valid stream"),
        );
        let u = |i: u64| d.unit(i).clamp(1e-12, 1.0 - 1e-12);
        let i_deg = INCLINATION_SCALE_DEG * m::sqrt(-2.0 * m::ln(u(0)));
        let mass_me = w.mass_earth
            + if w.envelope == Envelope::Giant {
                p.gas
            } else {
                0.0
            };
        planets.push(PlanetSpec {
            name: p.address.to_string(),
            address: p.address.to_string(),
            mass_me,
            a_au: p.a_au,
            e: p.e.clamp(0.0, 0.9),
            i_deg,
            node_deg: 360.0 * u(1),
            varpi_deg: 360.0 * u(2),
            mean_longitude_deg: 360.0 * u(3),
            oceans: w.envelope != Envelope::Giant && !w.desiccated && w.surface_water_oceans > 0.01,
        });
    }
    planets.sort_by(|a, b| a.a_au.total_cmp(&b.a_au));
    let debris = run.leftovers.as_ref().and_then(|l| {
        l.clouds
            .iter()
            .filter(|c| c.around.is_none())
            .max_by(|a, b| a.mass_earth().total_cmp(&b.mass_earth()))
            .map(|c| DebrisSpec {
                name: c.kind.clone(),
                address: c.address.to_string(),
                a_in_au: c.a_min_au,
                a_out_au: c.a_max_au,
                mass_me: c.mass_earth(),
            })
    });
    SystemSpec {
        name: h.manifest.system.to_string(),
        system: h.manifest.system.to_string(),
        star_address: h.stars[0].address.to_string(),
        star_mass: h.stars[0].mass,
        z: h.inheritance.z,
        age_myr: h.inheritance.age_gyr * 1000.0,
        birth_year: (h.inheritance.born_gyr * 1e9) as i64,
        planets,
        debris,
        sources: format!(
            "generated by {} ({:?} block) from manifest {}",
            run.pipeline, run.block, h.manifest_hash
        ),
    }
}

/// Age a formed system from its present to `target_myr` (star age) and tell
/// the whole story, formation and ageing, in date order.
pub fn long_life(
    run: &SystemRun,
    settings: &TimeSettings,
    target_myr: f64,
) -> Result<LongLife, String> {
    let spec = spec_from_run(run);
    let aged = Ageing::new(settings, &spec)?.run(target_myr);
    let mut story: Vec<StoryLine> = run
        .history
        .events
        .iter()
        .chain(run.events.iter())
        .map(|e| StoryLine {
            age_myr: e.t_myr,
            kind: e.kind.clone(),
            subjects: vec![e.subject.to_string()],
            text: e.text.clone(),
            from: "formation".into(),
        })
        .collect();
    let binaries: Vec<_> = crate::binary::interactions(
        &run.history,
        &settings.star,
        &crate::binary::BinaryRules::default(),
    )
    .into_iter()
    .filter(|i| i.age_myr <= target_myr)
    .collect();
    story.extend(binaries.iter().map(|i| StoryLine {
        age_myr: i.age_myr,
        kind: i.outcome.clone(),
        subjects: i.event.subjects.clone(),
        text: i.event.why.clone(),
        from: "ageing".into(),
    }));
    story.extend(aged.events.iter().map(|e| StoryLine {
        age_myr: e.age_myr,
        kind: e.kind.clone(),
        subjects: e.subjects.clone(),
        text: e.why.clone(),
        from: "ageing".into(),
    }));
    // Stable: equal dates keep formation before ageing, each in its own order.
    story.sort_by(|a, b| a.age_myr.total_cmp(&b.age_myr));
    Ok(LongLife {
        spec,
        run: aged,
        binaries,
        story,
    })
}
