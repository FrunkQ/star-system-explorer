//! Stable hierarchical addresses (H5.1).
//!
//! Text form: `u:<universe>/sys:12/body:3/shell:atm`. Each segment is
//! `kind:key`. The kind is a lowercase identifier; the key is any non-empty
//! run of `[A-Za-z0-9._:@-]` (patch keys contain colons, e.g. `patch:3:1a2f`,
//! so a segment splits on its first colon only).
//!
//! Generated children use the index the parent's resolve gave them (a decimal
//! key). Authored children live in their own namespace: keys starting with `@`
//! (`body:@1`), which generated keys never use, so they cannot collide.
//! Renaming changes a label, never an address.

use serde::{Deserialize, Serialize};
use std::fmt;
use std::str::FromStr;

#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub struct Segment {
    kind: String,
    key: String,
}

impl Segment {
    pub fn new(kind: &str, key: &str) -> Result<Self, AddressError> {
        if kind.is_empty()
            || !kind.as_bytes()[0].is_ascii_lowercase()
            || !kind
                .bytes()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'_')
        {
            return Err(AddressError::BadKind(kind.to_owned()));
        }
        if key.is_empty()
            || !key
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || b"._:@-".contains(&c))
        {
            return Err(AddressError::BadKey(key.to_owned()));
        }
        if key.starts_with('@') && key.len() == 1 {
            return Err(AddressError::BadKey(key.to_owned()));
        }
        Ok(Segment {
            kind: kind.to_owned(),
            key: key.to_owned(),
        })
    }
    pub fn kind(&self) -> &str {
        &self.kind
    }
    pub fn key(&self) -> &str {
        &self.key
    }
    pub fn is_authored(&self) -> bool {
        self.key.starts_with('@')
    }
}

/// A stable address. Always starts with a `u:` universe segment.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub struct Address {
    segments: Vec<Segment>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AddressError {
    Empty,
    NoUniverseRoot,
    BadSegment(String),
    BadKind(String),
    BadKey(String),
}
impl fmt::Display for AddressError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}
impl std::error::Error for AddressError {}

impl Address {
    pub fn universe(id: &str) -> Result<Self, AddressError> {
        Ok(Address {
            segments: vec![Segment::new("u", id)?],
        })
    }
    /// Child generated by a resolve, at `index` within the parent.
    pub fn child(&self, kind: &str, index: u64) -> Result<Self, AddressError> {
        self.child_key(kind, &index.to_string())
    }
    /// Child in the authored namespace (`@n`).
    pub fn authored_child(&self, kind: &str, n: u64) -> Result<Self, AddressError> {
        self.child_key(kind, &format!("@{n}"))
    }
    /// Child with an explicit key (e.g. a patch's `level:morton`).
    pub fn child_key(&self, kind: &str, key: &str) -> Result<Self, AddressError> {
        if kind == "u" {
            return Err(AddressError::BadKind(kind.into()));
        }
        let mut s = self.segments.clone();
        s.push(Segment::new(kind, key)?);
        Ok(Address { segments: s })
    }
    pub fn parent(&self) -> Option<Self> {
        (self.segments.len() > 1).then(|| Address {
            segments: self.segments[..self.segments.len() - 1].to_vec(),
        })
    }
    pub fn segments(&self) -> &[Segment] {
        &self.segments
    }
    pub fn last(&self) -> &Segment {
        self.segments.last().expect("never empty")
    }
    pub fn depth(&self) -> usize {
        self.segments.len()
    }
    /// True if `self` is `other` or one of its ancestors.
    pub fn contains(&self, other: &Address) -> bool {
        other.segments.len() >= self.segments.len()
            && other.segments[..self.segments.len()] == self.segments[..]
    }
}

impl fmt::Display for Address {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (i, s) in self.segments.iter().enumerate() {
            if i > 0 {
                f.write_str("/")?;
            }
            write!(f, "{}:{}", s.kind, s.key)?;
        }
        Ok(())
    }
}

impl FromStr for Address {
    type Err = AddressError;
    fn from_str(t: &str) -> Result<Self, AddressError> {
        if t.is_empty() {
            return Err(AddressError::Empty);
        }
        let mut segments = Vec::new();
        for part in t.split('/') {
            let (k, v) = part
                .split_once(':')
                .ok_or_else(|| AddressError::BadSegment(part.into()))?;
            segments.push(Segment::new(k, v)?);
        }
        if segments[0].kind != "u" || segments[1..].iter().any(|s| s.kind == "u") {
            return Err(AddressError::NoUniverseRoot);
        }
        Ok(Address { segments })
    }
}

impl Serialize for Address {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&self.to_string())
    }
}
impl<'de> Deserialize<'de> for Address {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        String::deserialize(d)?
            .parse()
            .map_err(serde::de::Error::custom)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use proptest::prelude::*;

    #[test]
    fn parse_display_and_namespaces() {
        let a: Address = "u:demo/patch:3:1a2f/sys:12/body:@1".parse().unwrap();
        assert_eq!(a.to_string(), "u:demo/patch:3:1a2f/sys:12/body:@1");
        assert!(a.last().is_authored());
        let g = a.parent().unwrap().child("body", 1).unwrap();
        assert_ne!(g, a, "authored and generated children never collide");
        assert!(a.parent().unwrap().contains(&a));
        assert!(!a.contains(&a.parent().unwrap()));
        for bad in [
            "",
            "sys:1",
            "u:x/u:y",
            "u:x/Body:1",
            "u:x/body:",
            "u:x/body:a b",
            "u:x//sys:1",
            "u:x/body:@",
        ] {
            assert!(
                bad.parse::<Address>().is_err(),
                "{bad:?} should be rejected"
            );
        }
    }

    proptest! {
        #[test]
        fn round_trip(ids in proptest::collection::vec((0u64..1000, any::<bool>()), 0..6)) {
            let mut a = Address::universe("p").unwrap();
            for (n, authored) in ids {
                a = if authored { a.authored_child("body", n).unwrap() } else { a.child("body", n).unwrap() };
            }
            let back: Address = a.to_string().parse().unwrap();
            prop_assert_eq!(&back, &a);
            let enc = crate::cbor::to_canonical(&a).unwrap();
            prop_assert_eq!(crate::cbor::from_canonical::<Address>(&enc).unwrap(), a);
        }
    }
}
