#!/usr/bin/env python3
"""RS1 part 2: cross-check the Sol today catalogue against Wikidata (CC0).

Usage: python3 -I scripts/spaceflight/crosscheck_wikidata.py <wikidata sparql json> <catalogue.json> <report.md>

The SPARQL query (run at https://query.wikidata.org/sparql, results as JSON):
  SELECT ?item ?cospar ?mass ?unit ?launch WHERE { ?item wdt:P247 ?cospar .
    OPTIONAL { ?item p:P2067/psv:P2067 [wikibase:quantityAmount ?mass; wikibase:quantityUnit ?unit] }
    OPTIONAL { ?item wdt:P619 ?launch } FILTER(STRLEN(?cospar) <= 10) }
Adds each craft's Wikidata id to the catalogue (key "wikidata") and writes a report of every launch
date that differs and every mass that differs by more than 10 percent. Nothing in GCAT is overwritten:
GCAT stays the source, and a disagreement is something to read the primary source for.
"""
import json, sys, datetime

UNITS = {"Q11570": 1.0, "Q191118": 1000.0, "Q41803": 0.001}  # kilogram, tonne, gram
MONTHS = {m: i + 1 for i, m in enumerate("Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split())}

wd_path, cat_path, rep_path = sys.argv[1:4]
wd = {}
for b in json.load(open(wd_path))["results"]["bindings"]:
    c = b["cospar"]["value"].strip()
    e = wd.setdefault(c, {"items": set(), "mass": set(), "launch": set()})
    e["items"].add(b["item"]["value"].rsplit("/", 1)[1])
    if "mass" in b and b.get("unit", {}).get("value", "").rsplit("/", 1)[-1] in UNITS:
        e["mass"].add(round(float(b["mass"]["value"]) * UNITS[b["unit"]["value"].rsplit("/", 1)[1]], 3))
    if "launch" in b:
        e["launch"].add(b["launch"]["value"][:10])

def gcat_day(s):
    p = s.split()
    if len(p) < 3 or p[1] not in MONTHS:
        return None
    try:
        return datetime.date(int(p[0]), MONTHS[p[1]], int(p[2].rstrip("?"))).isoformat()
    except ValueError:
        return None

cat = json.load(open(cat_path))
found, dates, masses = 0, [], []
for c in cat["departed"]:
    e = wd.get(c["piece"])
    if not e:
        continue
    found += 1
    c["wikidata"] = sorted(e["items"])[0]
    g = gcat_day(c["launched"])
    if g and e["launch"] and g not in e["launch"]:
        # a launch just before midnight UTC can carry the next local date: allow one day
        gd = datetime.date.fromisoformat(g)
        if all(abs((datetime.date.fromisoformat(w) - gd).days) > 1 for w in e["launch"] if len(w) == 10 and w[4] == "-"):
            dates.append((c["piece"], c["name"], g, sorted(e["launch"])))
    if "mass_kg" in c and c["mass_kg"] and e["mass"]:
        m = c["mass_kg"]
        if all(abs(w - m) / m > 0.10 for w in e["mass"]):
            masses.append((c["piece"], c["name"], m, sorted(e["mass"])))
with open(cat_path, "w", encoding="utf-8") as f:
    json.dump(cat, f, ensure_ascii=False, separators=(",", ":"))
    f.write("\n")
n = len(cat["departed"])
lines = [
    "# RS1 part 2: catalogue against Wikidata",
    "",
    "Generated by `scripts/spaceflight/crosscheck_wikidata.py`. GCAT stays the source; each row below is a disagreement to settle from a primary source (mission report, agency fact sheet), not a correction.",
    "",
    f"- Craft that left Earth orbit: {n}; found in Wikidata by COSPAR id: {found}.",
    f"- Launch dates that differ by more than a day: {len(dates)}.",
    f"- Masses that differ by more than 10 percent: {len(masses)}. Pioneer 10 is a Wikidata error (it launched on 3 March 1972, as GCAT says). Most mass rows are a different mass being quoted (launch mass with propellant against dry mass, or a probe with or without its lander), which RS2's parts settle.",
    "",
    "## Launch dates",
    "",
    "| COSPAR | Name | GCAT | Wikidata |",
    "|---|---|---|---|",
] + [f"| {p} | {nm} | {g} | {', '.join(w)} |" for p, nm, g, w in dates] + [
    "",
    "## Masses (kg)",
    "",
    "| COSPAR | Name | GCAT | Wikidata |",
    "|---|---|---|---|",
] + [f"| {p} | {nm} | {m} | {', '.join(str(x) for x in w)} |" for p, nm, m, w in masses]
open(rep_path, "w").write("\n".join(lines) + "\n")
print(n, found, len(dates), len(masses))
