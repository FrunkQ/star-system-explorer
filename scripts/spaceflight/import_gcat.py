#!/usr/bin/env python3
"""RS1: build the Sol today catalogue from Jonathan McDowell's GCAT (CC BY 4.0).

Usage: python3 -I scripts/spaceflight/import_gcat.py <dir with GCAT .tsv files> <out dir>

Download the files from https://planet4589.org/space/gcat/tsv/ first:
  launch/launch.tsv cat/deepcat.tsv cat/hcocat.tsv cat/lprcat.tsv cat/landercat.tsv cat/psatcat.tsv
Writes <out dir>/catalogue.json: the wide, thin level of track RS (design section 3, level 1).
The output is sorted and has no timestamps of its own, so the same GCAT release gives the same bytes.
"""
import json, sys, os, re

def rd(path):
    rows, head = [], None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if not line.strip():
                continue
            if head is None:
                head = line.lstrip("#").rstrip("\n").split("\t")
                continue
            if line.startswith("#"):
                continue
            rows.append(dict(zip(head, [x.strip() for x in line.rstrip("\n").split("\t")])))
    return rows

def num(s):
    s = (s or "").strip()
    if s in ("", "-", "?"):
        return None
    try:
        v = float(s)
    except ValueError:
        return None
    return int(v) if v == int(v) else v

def updated(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"# Updated (.*)", line)
            if m:
                return m.group(1).strip()
    return None

src, out = sys.argv[1], sys.argv[2]
P = lambda n: os.path.join(src, n)

# Launches: orbital attempts only (GCAT LaunchCode starts with O: OS success, OF failure, and so on).
launches = []
for x in rd(P("launch.tsv")):
    code = x.get("LaunchCode", "")
    if not code.startswith("O"):
        continue
    launches.append([x["Launch_Tag"], x["Launch_Date"], x["LV_Type"], x["Launch_Site"], x["Launch_Pad"],
                     code, x.get("Dest", "-"), num(x.get("OrbPay"))])
launches.sort(key=lambda r: r[0])

# Everything that left Earth orbit: payloads (Type P) in the deep-space, heliocentric and lunar and
# planetary registers. GCAT keeps one row per orbit phase; the phase count is kept here as a pointer
# for RS8, and the first row gives the launch facts.
craft, phases = {}, {}
for cat in ("deepcat", "hcocat", "lprcat"):
    for x in rd(P(cat + ".tsv")):
        if not x["Type"].startswith("P"):
            continue
        j = x["JCAT"]
        phases.setdefault(j, set()).add((cat, x["ODate"], x["Primary"], x["Dest"]))
        if j in craft:
            continue
        craft[j] = {
            "jcat": j, "piece": x["Piece"], "name": x["Name"], "launched": x["LDate"],
            "owner": x["Owner"], "state": x["State"], "status": x["Status"],
            "mass_kg": num(x["Mass"]), "dry_mass_kg": num(x["DryMass"]),
            "length_m": num(x["Length"]), "diameter_m": num(x["Diameter"]), "span_m": num(x["Span"]),
            "shape": x["Shape"] if x["Shape"] not in ("", "-") else None,
        }
for j, c in craft.items():
    ph = sorted(phases[j], key=lambda p: (p[1], p[0]))
    c["phases"] = len(ph)
    dests = []
    for p in ph:
        d = p[3]
        if d not in ("-", "") and not d.startswith("D0") and d not in dests:
            dests.append(d)
    c["destinations"] = dests
    c = {k: v for k, v in c.items() if v is not None}
    craft[j] = c
departed = [craft[j] for j in sorted(craft)]

landings = []
for x in rd(P("landercat.tsv")):
    landings.append({k: v for k, v in {
        "jcat": x["JCAT"], "piece": x["Piece"], "name": x["Name"], "world": x["World"],
        "lon_deg": num(x["Lon"]), "lat_deg": num(x["Lat"]), "kind": x["LType"], "status": x["Status"],
        "landed": x["LandDate"], "ended": x["OffDate"], "site": x["LSite"] if x["LSite"] not in ("-", "") else None,
    }.items() if v is not None})
landings.sort(key=lambda r: (r["jcat"], r.get("landed", "")))

# Crewed craft: GCAT payload category SS (human spaceflight vehicles, crewed or flown as their tests).
crewed = []
for x in rd(P("psatcat.tsv")):
    if x["Category"] == "SS":
        crewed.append([x["JCAT"], x["Piece"], x["Name"], x["LDate"], x["Program"]])
crewed.sort(key=lambda r: r[0])

doc = {
    "about": "Sol today catalogue (track RS1): the wide, thin level for every orbital launch, every craft that left Earth orbit, every landing or impact on another world, and every human spaceflight vehicle. Generated by scripts/spaceflight/import_gcat.py; do not edit by hand.",
    "credit": "Data from GCAT: General Catalog of Artificial Space Objects, Jonathan C. McDowell, https://planet4589.org/space/gcat/ , released under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Rearranged and filtered for SSE4; no values changed.",
    "gcat_updated": {f: updated(P(f + ".tsv")) for f in ("launch", "deepcat", "hcocat", "lprcat", "landercat", "psatcat")},
    "counts": {"orbital_launches": len(launches), "departed_payloads": len(departed),
               "landings_and_impacts": len(landings), "crewed_vehicle_records": len(crewed)},
    "launch_columns": ["tag", "date_utc", "vehicle", "site", "pad", "gcat_launch_code", "dest", "orbital_payload_t"],
    "launches": launches,
    "departed": departed,
    "landings": landings,
    "crewed_columns": ["jcat", "piece", "name", "launched", "program"],
    "crewed": crewed,
}
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "catalogue.json"), "w", encoding="utf-8") as f:
    json.dump(doc, f, ensure_ascii=False, separators=(",", ":"), sort_keys=False)
    f.write("\n")
print(json.dumps(doc["counts"]))
