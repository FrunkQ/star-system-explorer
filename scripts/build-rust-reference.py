#!/usr/bin/env python3
"""The kernel's compiled copy of the master data sheet's constants (MP22 part 2).

Compiled code that needs a constant's unedited value (a unit factor, a const
fn, a table built at start-up) reads it from crates/sse-core/src/sheet.rs,
which this script writes from packs/base-reference. Every value is the
sheet's own number, written as Python's shortest round-trip form, so Rust
reads back the same f64 bit for bit. Edits to the sheet reach blocks through
the constants handle and the reader, never through this file: these are the
sheet's defaults, in one place, so no crate types its own copy.

The file is generated: never edit it. The sse-reference test
`the_compiled_sheet_is_the_base_sheet` fails when it is stale.

  scripts/build-rust-reference.py          write the file
  scripts/build-rust-reference.py --check  exit 1 if the file is stale
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEET = os.path.join(ROOT, "packs", "base-reference", "pack.json")
OUT = os.path.join(ROOT, "crates", "sse-core", "src", "sheet.rs")


def ident(row_id):
    name = re.sub(r"\W", "_", row_id).upper()
    if not re.fullmatch(r"[A-Z_][A-Z0-9_]*", name):
        raise SystemExit(f"build-rust-reference: sheet id {row_id!r} makes no Rust name")
    return name


def lit(v):
    s = repr(float(v))
    if s in ("inf", "-inf", "nan"):
        raise SystemExit(f"build-rust-reference: {v} is not a finite number")
    return s


def build():
    with open(SHEET, encoding="utf-8") as f:
        pack = json.load(f)
    rows = pack["provides"]["reference"]["constants"]
    out = [
        "//! Generated by scripts/build-rust-reference.py from packs/base-reference",
        "//! (the master data sheet). Do not edit: change the sheet and run the script.",
        "//!",
        "//! The sheet's constants at their unedited values, for compiled code. An edit",
        "//! to the sheet reaches a block through `sse_core::constants` (the handle) or",
        "//! the reader, not through these.",
        "#![allow(clippy::excessive_precision, clippy::approx_constant)]",
        "",
    ]
    names = []
    for r in rows:
        name = ident(r["id"])
        v = r["value"]
        out.append(f"/// `{r['id']}`: {r['name']} ({v['unit']}; {v['src']}).")
        out.append(f"pub const {name}: f64 = {lit(v['v'])};")
        names.append((r["id"], name))
    out.append("")
    out.append("/// Every constant above by its sheet id, in sheet order.")
    out.append("pub const ALL: [(&str, f64); %d] = [" % len(names))
    for rid, name in names:
        out.append(f"    ({json.dumps(rid)}, {name}),")
    out.append("];")
    ref = pack["provides"]["reference"]
    # Standard atomic weights, g/mol, by symbol (the elements with no stable
    # isotope have none).
    weights = {}
    out += ["", "/// Standard atomic weights, g/mol, by element (IUPAC, as on the sheet).", "pub mod atomic_weight {"]
    for e in ref["elements"]:
        w = e.get("atomic_weight")
        if w is None:
            continue
        weights[e["id"]] = w["v"]
        out.append(f"    /// {e['name']} ({w['src']}).")
        out.append(f"    pub const {ident(e['symbol'])}: f64 = {lit(w['v'])};")
    out.append("}")
    # Molar masses, kg/mol, worked out from each substance's formula exactly
    # as the reader does (elements in id order, sum, then / 1000).
    masses = {}
    for i in ref.get("isotopes", []):
        if isinstance(i.get("mass"), dict):
            masses[i["id"]] = i["mass"]["v"]
    out += ["", "/// Molar masses, kg/mol, worked out from each substance's formula (as the reader does).", "pub mod molar_mass {"]
    for sub in ref["substances"]:
        f = sub.get("formula") or {}
        total, ok = 0.0, bool(f)
        for el in sorted(f):
            w = weights.get(el, masses.get(el))
            if w is None:
                ok = False
                break
            total += f[el] * w
        if ok:
            out.append(f"    /// {sub['id']}.")
            out.append(f"    pub const {ident(sub['id'])}: f64 = {lit(total / 1000.0)};")
    out.append("}")
    # A few phase properties every crate reaches for, per substance that has
    # them (the reader holds the rest).
    for prop, doc in [("triple_point_k", "Triple point temperature, K"), ("triple_point_pa", "Triple point pressure, Pa"),
                      ("density_solid", "Density of the solid at its reference state, kg/m3"),
                      ("density_liquid", "Density of the liquid at its reference state, kg/m3"),
                      ("latent_vaporisation", "Latent heat of vaporisation, J/kg")]:
        rows = [(sub["id"], sub["phases"][prop]) for sub in ref["substances"]
                if isinstance(sub.get("phases", {}).get(prop), dict) and isinstance(sub["phases"][prop].get("v"), (int, float))]
        out += ["", f"/// {doc}, by substance (the sheet's `phases.{prop}`).", f"pub mod {prop} {{"]
        for sid, v in rows:
            out.append(f"    /// {sid} ({v.get('src', '')}).")
            out.append(f"    pub const {ident(sid)}: f64 = {lit(v['v'])};")
        out.append("}")
    # The conductivity fit of the solid (k = a / T and the like): its coefficients.
    out += ["", "/// Thermal conductivity fits of the solid, by substance (the sheet's `thermal.conductivity_solid`):", "/// the coefficients, in the order the fit names them.", "pub mod conductivity_solid {"]
    for sub in ref["substances"]:
        fit = (sub.get("thermal") or {}).get("conductivity_solid")
        if isinstance(fit, dict) and fit.get("coeffs"):
            co = ", ".join(lit(c) for c in fit["coeffs"])
            out.append(f"    /// {sub['id']}: {fit['fit']} ({fit.get('unit', '')}; {fit.get('src', '')}).")
            out.append(f"    pub const {ident(sub['id'])}: [f64; {len(fit['coeffs'])}] = [{co}];")
    out.append("}")
    # Isotope properties, by isotope id (the sheet's isotopes table).
    for prop, doc in [("half_life_s", "Half-life, s"), ("decay_heat_w_per_kg", "Decay heat, W per kg of the isotope"),
                      ("share_at_sun_birth", "Share at the Sun's birth (as each row's note says)"),
                      ("share_today", "Mass share of its element today")]:
        out += ["", f"/// {doc}, by isotope (the sheet's isotopes).", f"pub mod isotope_{prop} {{"]
        for iso in ref.get("isotopes", []):
            v = iso.get(prop)
            if isinstance(v, dict) and isinstance(v.get("v"), (int, float)):
                out.append(f"    /// {iso['id']} ({v.get('src', '')}).")
                out.append(f"    pub const {ident(iso['id'])}: f64 = {lit(v['v'])};")
        out.append("}")
    # The protosolar mixture's mass shares, worked out from the elements'
    # protosolar abundances and atomic weights (elements in sheet order).
    total, h, he = 0.0, 0.0, 0.0
    for e in ref["elements"]:
        a, w = e.get("abundance_protosolar"), e.get("atomic_weight")
        if isinstance(a, dict) and isinstance(w, dict):
            x = a["v"] * w["v"]
            total += x
            if e["id"] == "h":
                h = x
            elif e["id"] == "he":
                he = x
    out += ["", "/// The protosolar mixture's mass shares, from every element's protosolar abundance",
            "/// times its atomic weight (the sheet's elements).", "pub mod protosolar {",
            "    /// X, the mass share of hydrogen.", f"    pub const X: f64 = {lit(h / total)};",
            "    /// Y, the mass share of helium.", f"    pub const Y: f64 = {lit(he / total)};",
            "    /// Z, the mass share of everything heavier.", f"    pub const Z: f64 = {lit((total - h - he) / total)};", "}"]
    # Mixture properties, by mixture id.
    for prop, doc in [("density", "Density, kg/m3"), ("yield_strength", "Yield strength, Pa")]:
        out += ["", f"/// {doc}, by mixture (the sheet's mixtures).", f"pub mod mixture_{prop} {{"]
        for mx in ref["mixtures"]:
            v = mx.get(prop)
            if isinstance(v, dict) and isinstance(v.get("v"), (int, float)):
                out.append(f"    /// {mx['id']} ({v.get('src', '')}).")
                out.append(f"    pub const {ident(mx['id'])}: f64 = {lit(v['v'])};")
        out.append("}")
    # Unit factors to SI, by unit id.
    out += ["", "/// Each unit's factor to SI, by unit id (the sheet's units table).", "pub mod unit {"]
    for u in ref["units"]:
        fv = (u.get("factor") or {}).get("v")
        if isinstance(fv, (int, float)):
            out.append(f"    /// {u['name']}.")
            out.append(f"    pub const {ident(u['id'])}: f64 = {lit(fv)};")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print("build-rust-reference: %s is stale; run scripts/build-rust-reference.py" % os.path.relpath(OUT, ROOT))
            sys.exit(1)
        print("build-rust-reference: up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("build-rust-reference: wrote %s" % os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
