#!/usr/bin/env python3
"""The interface's copy of the master data sheet's constants (MP22, UI side).

The chart room needs a handful of constants (and the small Bands table) synchronously (the astronomical
unit, the Sun's and Earth's masses and radii, the speed of light). Bundling all
of packs/base-reference (about 350 kB of elements, isotopes and substances)
into the page for them would be wasteful, so this writes just the constants,
unchanged, and each unit's factor to SI, to packages/ui-contract/generated/reference-constants.json,
which ui-contract's sheet.ts reads. The file is generated: never edit it.
packages/ui-contract/test/sheet.test.ts fails when it is stale.

  scripts/build-ui-reference.py          write the file
  scripts/build-ui-reference.py --check  exit 1 if the file is stale
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEET = os.path.join(ROOT, "packs", "base-reference", "pack.json")
OUT = os.path.join(ROOT, "packages", "ui-contract", "generated", "reference-constants.json")


def unit_factor(u, consts):
    """A unit's factor to SI: its `factor_from` worked out over the constants
    (numbers and ids multiplied, `/` dividing by the next), else its typed factor."""
    f = u.get("factor_from")
    if not f:
        return u["factor"]["v"]
    v, div = 1.0, False
    for tok in f.split():
        if tok == "/":
            div = True
            continue
        x = math.pi if tok == "pi" else consts[tok]["v"] if tok in consts else float(tok)
        v = v / x if div else v * x
        div = False
    return v


def build():
    with open(SHEET, encoding="utf-8") as f:
        pack = json.load(f)
    consts = {c["id"]: {k: c["value"][k] for k in ("v", "unit", "src")} for c in pack["provides"]["reference"]["constants"]}
    doc = {
        "about": "Generated by scripts/build-ui-reference.py from packs/base-reference: the master data sheet's constants, unchanged. Do not edit.",
        "pack": {"id": pack["id"], "version": pack["version"]},
        "constants": consts,
        # Each unit's factor to SI, for documents that give a value in a unit.
        "units": {u["id"]: unit_factor(u, consts) for u in pack["provides"]["reference"]["units"]},
        # The Bands table (RK10), small and read by every screen's band list:
        # id, kind, plain name, wavelength range in metres, view and recipe.
        "bands": [{k: v for k, v in {
            "id": b["id"], "kind": b["kind"], "name": b["names"]["physics"], "plain": b["names"]["plain"],
            "view_id": b.get("view_id"), "view": b.get("view"), "recipe": b.get("recipe"),
            "from_m": b["from_m"]["v"] if "from_m" in b else None, "to_m": b["to_m"]["v"] if "to_m" in b else None,
        }.items() if v is not None} for b in pack["provides"]["reference"].get("bands", [])],
    }
    return json.dumps(doc, indent=1, sort_keys=False, ensure_ascii=False) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("build-ui-reference: %s is stale; run scripts/build-ui-reference.py" % os.path.relpath(OUT, ROOT))
                sys.exit(1)
        print("build-ui-reference: up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("build-ui-reference: wrote %s" % os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
