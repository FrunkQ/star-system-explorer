// The minimum spec table (PF3, handover/design/SSE4-performance-and-minimum-spec.md): reads every
// sse.perf-report/1 under docs/perf-reports/ and writes docs/minimum-spec.md. The table is regenerated, never typed.
// Usage: node scripts/min-spec.mjs            (writes the file)
//        node scripts/min-spec.mjs --check    (exit 1 when the file is out of date)
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const dir = join(root, "docs/perf-reports");
const target = join(root, "docs/minimum-spec.md");
const doc = JSON.parse(readFileSync(join(root, "packages/ui-contract/src/perf-chunks.json"), "utf8"));

const walk = (d) => (existsSync(d) ? readdirSync(d).sort().flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : n.endsWith(".json") ? [join(d, n)] : [])) : []);
const reports = walk(dir)
  .map((f) => ({ file: relative(root, f), ...JSON.parse(readFileSync(f, "utf8")) }))
  .filter((r) => r.schema === "sse.perf-report/1");
const app = reports.filter((r) => r.source === "app");
const bench = reports.filter((r) => r.source === "bench");

const ms = (x) => (x === undefined ? "" : x >= 1000 ? `${(x / 1000).toFixed(x >= 10_000 ? 0 : 1)} s` : `${x >= 100 ? Math.round(x) : x.toFixed(1)} ms`);
const gpu = (d) => (d.gpu?.backend && d.gpu.backend !== "none" ? d.gpu.backend : "no GPU");
const cls = (d) => [d.tier ?? "unmeasured", gpu(d)].join(", ");
const speed = (r) => r.device?.units_per_second ?? 0;
const name = (r) => r.label || r.file;

const out = [];
out.push("# Minimum spec");
out.push("");
out.push("Generated by `node scripts/min-spec.mjs` from the reports in `docs/perf-reports/`; do not edit by hand. Design: `handover/design/SSE4-performance-and-minimum-spec.md`.");
out.push("");
out.push("A report comes from the chart room (More › Performance readout › Copy report or Save) or from the bench on `/harness/` (Run the bench › Copy report or Save), or from `node tests/harness/bench.mjs --out <dir>`. Save it in `docs/perf-reports/` under a short name and run the script.");
out.push("");
out.push("## Minimum spec by chunk");
out.push("");
out.push("From app reports: a device meets a chunk's minimum spec when the chunk's 95th percentile stays within its budget. The minimum spec is the slowest device (by the kernel's measured speed) that meets it.");
out.push("");
out.push("| Chunk | Budget | Minimum spec so far | Devices over budget |");
out.push("|---|---|---|---|");
for (const c of doc.chunks) {
  const seen = app.map((r) => ({ r, c: r.chunks.find((x) => x.id === c.id) })).filter((x) => x.c);
  const ok = seen.filter((x) => x.c.p95_ms <= c.budget_ms).sort((a, b) => speed(a.r) - speed(b.r));
  const over = seen.filter((x) => x.c.p95_ms > c.budget_ms).map((x) => `${name(x.r)} (${ms(x.c.p95_ms)})`);
  const min = ok[0] ? `${name(ok[0].r)}: ${cls(ok[0].r.device)} (${ms(ok[0].c.p95_ms)})` : seen.length ? "none yet" : "not measured yet";
  out.push(`| ${c.name} | ${ms(c.budget_ms)} | ${min} | ${over.join("; ")} |`);
}
out.push("");

if (app.length) {
  out.push("## App reports: 95th percentile by chunk");
  out.push("");
  out.push(`| Chunk | ${app.map(name).join(" | ")} |`);
  out.push(`|---|${app.map(() => "---").join("|")}|`);
  for (const c of doc.chunks) {
    const cells = app.map((r) => {
      const x = r.chunks.find((y) => y.id === c.id);
      return x ? `${ms(x.p95_ms)} ${x.p95_ms <= c.budget_ms ? "within" : "over"}` : "";
    });
    if (cells.some(Boolean)) out.push(`| ${c.name} | ${cells.join(" | ")} |`);
  }
  out.push("");
}

if (bench.length) {
  out.push("## Bench: the same work on every device");
  out.push("");
  out.push("Each chunk is the sum of its engine scenarios' medians. In brackets, how many times slower than the fastest device listed. These are test workloads, so they have no budget; they show how machines compare, and a chunk's app timings on one device can be scaled by its bench ratio to estimate another.");
  out.push("");
  out.push(`| Chunk | ${bench.map(name).join(" | ")} |`);
  out.push(`|---|${bench.map(() => "---").join("|")}|`);
  for (const c of [...doc.chunks, { id: "other", name: "Other" }]) {
    const vals = bench.map((r) => r.chunks.find((y) => y.id === c.id)?.median_ms);
    if (!vals.some((v) => v !== undefined)) continue;
    const best = Math.min(...vals.filter((v) => v !== undefined));
    const shaky = bench.map((r) => (r.chunks.find((y) => y.id === c.id)?.sources ?? []).some((x) => x.unsteady || (x.max_ms > 2 * x.median_ms && x.max_ms - x.median_ms > 50)));
    out.push(`| ${c.name} | ${vals.map((v, i) => (v === undefined ? "" : `${ms(v)} (${(v / best).toFixed(1)}×)${shaky[i] ? " ‡" : ""}`)).join(" | ")} |`);
  }
  if (bench.some((r) => r.chunks.some((c) => c.sources.some((x) => x.unsteady || (x.max_ms > 2 * x.median_ms && x.max_ms - x.median_ms > 50))))) out.push("", "‡ One run of a scenario took over twice its median, the mark of a pause on the device (screen dimmed, another app); the median is still used.");
  out.push("");
}

const drawn = bench.filter((r) => r.drawing);
if (drawn.length) {
  // VP4: the speed probe's three scenes on each device's graphics, and the tier its speed earns for the standard True
  // recipe at 1080p (handover/design/SSE4-visual-polish-design.md 8.1 to 8.3).
  const words = { "gpu-ultra": "Ultra", "gpu-high": "High", "gpu-basic": "Light", canvas: "2D canvas", text: "Words only" };
  out.push("## Drawing: the speed probe by device");
  out.push("");
  out.push("The probe's three scenes at one megapixel (fill, march, geometry), in ms and as a factor of the reference device, and the tier this speed earns for the standard True recipe at 1080p: the richest whose predicted frame is within 60% of its budget. Ultra also needs WebGPU with compute. The last column is the standard frame drawn for real at each tier (a star, eight worlds, a belt and the shared finish), from which the pass costs are set.");
  out.push("");
  out.push("| Report | Graphics | Fill | March | Geometry | Placed at | Predicted frame by tier | Drawn frame by tier |");
  out.push("|---|---|---|---|---|---|---|---|");
  for (const r of drawn) {
    const d = r.drawing;
    const sc = (k) => (d.scenes_ms?.[k] === undefined ? "" : `${d.scenes_ms[k].toFixed(2)} ms (${d.factors[k].toFixed(2)}×)`);
    const pred = (d.predictions ?? []).map((p) => `${words[p.tier] ?? p.tier} ${p.ms === null ? "no form" : `${p.ms.toFixed(1)} of ${Math.round(p.budget_ms)} ms`}`).join("; ");
    const gfx = [d.backend, d.method && d.method !== "none" ? d.method : null, d.steady === false ? "unsteady" : null, d.adapter].filter(Boolean).join(", ").replace(/\|/g, "/");
    // The standard frame drawn for real (bench reports from 25 Nov on); older reports have none.
    const drew = (d.standard ?? []).map((f) => `${words[f.tier] ?? f.tier} ${f.ms.toFixed(1)} ms`).join("; ");
    out.push(`| ${name(r)} | ${gfx} | ${sc("fill")} | ${sc("march")} | ${sc("geometry")} | ${words[d.earned] ?? d.earned ?? (d.error ? "could not draw" : "")} | ${pred} | ${drew || "not drawn"} |`);
  }
  out.push("");
}

out.push("## Devices");
out.push("");
if (!reports.length) out.push("No reports yet.");
else {
  out.push("| Report | Source | Day | Device | Class | Speed (units/s) |");
  out.push("|---|---|---|---|---|---|");
  for (const r of reports) {
    const d = r.device ?? {};
    const what = [d.cpu, d.cores ? `${d.cores} cores` : null, d.memory_gb ? `${d.memory_gb} GB` : null, d.gpu?.adapter, d.user_agent?.replace(/\s*\(.*?\)\s*/g, " ").trim(), d.note].filter(Boolean).join("; ");
    out.push(`| ${name(r)} (\`${r.file}\`) | ${r.source} | ${r.made_on} | ${what.replace(/\|/g, "/")} | ${cls(d)} | ${d.units_per_second ? d.units_per_second.toLocaleString("en") : ""} |`);
  }
}
out.push("");

const text = out.join("\n");
if (process.argv.includes("--check")) {
  const now = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (now !== text) {
    console.log("docs/minimum-spec.md is out of date: run node scripts/min-spec.mjs");
    process.exit(1);
  }
  console.log("docs/minimum-spec.md is up to date");
} else {
  writeFileSync(target, text);
  console.log(`wrote docs/minimum-spec.md from ${reports.length} report${reports.length === 1 ? "" : "s"} (${app.length} app, ${bench.length} bench)`);
}
